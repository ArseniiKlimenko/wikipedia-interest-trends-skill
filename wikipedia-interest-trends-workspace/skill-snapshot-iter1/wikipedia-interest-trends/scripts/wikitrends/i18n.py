def tr(lang: str) -> dict:
    return T.get(lang, T["en"])


def lang_name(code: str, ui: str = "en") -> str:
    names = LANG_NAMES.get(code)
    if not names:
        return code
    return names[1] if ui == "uk" else names[0]


