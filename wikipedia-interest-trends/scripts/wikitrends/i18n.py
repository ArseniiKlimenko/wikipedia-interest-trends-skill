def tr(lang: str) -> dict:
    return T.get(lang, T["en"])


def lang_name(code: str, ui: str = "en") -> str:
    names = LANG_NAMES.get(code)
    if not names:
        return code
    return names[1] if ui == "uk" else names[0]


_UK_WIKI_ADJ = {"uk": "україномовній", "en": "англомовній", "fr": "франкомовній", "es": "іспаномовній",
                "pt": "португаломовній", "it": "італомовній", "simple": "спрощеній англійській"}


def wiki_phrase(code: str, ui: str = "en") -> str:
    """'in Polish Wikipedia' / 'у польськомовній Вікіпедії'."""
    if ui == "uk":
        name = LANG_NAMES.get(code, (code, code))[1]
        adj = _UK_WIKI_ADJ.get(code)
        if not adj and name.endswith("ська"):
            adj = name[:-4] + "ськомовній"
        if not adj and name.endswith("цька"):
            adj = name[:-4] + "цькомовній"
        if not adj:
            return "у Вікіпедії мовою %s (%s)" % (name, code)
        return ("в %s Вікіпедії" if adj[0] in "аеєиіїоуюя" else "у %s Вікіпедії") % adj
    name = LANG_NAMES.get(code, (code,))[0]
    return "in %s Wikipedia" % name if name != code else "in the %s Wikipedia" % code


def pct(x, digits: int = 0) -> str:
    if x is None:
        return "n/a"
    return ("%+." + str(digits) + "f%%") % (x * 100)


def fmt_int(x, ui: str = "en") -> str:
    if x is None:
        return "n/a"
    s = "{:,.0f}".format(x)
    return s.replace(",", " ") if ui == "uk" else s
